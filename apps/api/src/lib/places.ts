/**
 * What the sorter can say about where a picture was taken, without the internet: well-known landmarks and a few
 * dozen kinds of scenery, each scored zero-shot by the same picture model that files the pictures. A match is a
 * guess shown next to the file, and it is only believed when it clearly beats everything else on this list.
 */
export interface PlaceGuess {
    /** The text the picture model is asked to match; what the user sees is `place`. */
    prompt: string;
    place: string;
}

const landmark = (name: string, where: string): PlaceGuess => ({
    prompt: `the ${name} in ${where}`,
    place: `${name}, ${where}`,
});
const scene = (prompt: string, place: string): PlaceGuess => ({ prompt, place });

